"""Trace the reference drawings (ref/, not in the repo) into site/js/figures.js.

Run from the repo root:  python3 tools/trace/build_assets.py
"""
import sys, json, os
sys.path.insert(0, os.path.dirname(__file__))
import numpy as np, cv2
from centerline import load_gray, trace, binarize, smooth_d, soften, rdp, silhouette, UP
import head as headmod

M = 'ref/mani-pose.png'; C = 'ref/gatto-pose.png'


def fill_holes(m):
    h, w = m.shape
    pad = cv2.copyMakeBorder(m, 1, 1, 1, 1, cv2.BORDER_CONSTANT, value=0)
    ff = pad.copy(); mask = np.zeros((h + 4, w + 4), np.uint8)
    cv2.floodFill(ff, mask, (0, 0), 2)
    return (ff[1:-1, 1:-1] != 2).astype(np.uint8)


def contour_d(mask, up):
    cs, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    c = max(cs, key=cv2.contourArea)[:, 0, :].astype(float)
    c = rdp(soften(np.vstack([c, c[:1]]), 2.0 * up), 0.5 * up) / up
    return c


def hand(box, **o):
    x0, y0, x1, y1 = box
    g = load_gray(M)[y0:y1, x0:x1]
    r = trace(g, **o)
    sil = r['sil']
    yb = sil[:, 1].max()
    bottom = sil[sil[:, 1] > yb - 3]
    return dict(w=x1 - x0, h=y1 - y0, sil=smooth_d(sil, True), ink=''.join(smooth_d(l) for l in r['lines']),
                elbow=[round(float(bottom[:, 0].min() + bottom[:, 0].max()) / 2, 1), round(float(yb), 1)],
                sleeve=round(float(bottom[:, 0].max() - bottom[:, 0].min()), 1))


def cat(box):
    x0, y0, x1, y1 = box
    g = load_gray(C)[y0:y1, x0:x1]
    big = cv2.resize(g, None, fx=UP, fy=UP, interpolation=cv2.INTER_CUBIC)
    shade = (cv2.GaussianBlur(big, (0, 0), 3 * UP) < 250).astype(np.uint8)
    lines = binarize(g, 200)
    m = cv2.morphologyEx(shade | lines, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (31, 31)))
    m = fill_holes(m)
    n, lab, st, _ = cv2.connectedComponentsWithStats(m)
    m = (lab == 1 + np.argmax(st[1:, cv2.CC_STAT_AREA])).astype(np.uint8)
    r = trace(g, thr=200, keep_inside=False, close_bottom=False)
    allow = cv2.dilate(m, np.ones((15, 15), np.uint8))
    keep = [l for l in r['lines'] if allow[min(int(l[:, 1].mean() * UP), allow.shape[0] - 1), min(int(l[:, 0].mean() * UP), allow.shape[1] - 1)]]
    return dict(w=x1 - x0, h=y1 - y0, sil=smooth_d(contour_d(m, UP), True), ink=''.join(smooth_d(l) for l in keep))


def head():
    h = headmod.build()
    # silhouette of what is kept: hood and ear cups, closed along the crop border
    up = 2
    m = np.zeros((h['h'] * up, h['w'] * up), np.uint8)
    for l in h['lines']:
        cv2.polylines(m, [np.round(l * up).astype(np.int32)], False, 1, 2)
    cv2.fillPoly(m, [np.round(np.array(h['hair']) * up).astype(np.int32)], 1)
    sil = silhouette(m, True, close_px=9, close_sides=0.55)
    bo, bi = h['band']
    band = smooth_d(bo) + 'L' + ' L'.join(f'{x:.1f},{y:.1f}' for x, y in bi[::-1]) + 'Z'
    return dict(w=h['w'], h=h['h'], sil=smooth_d(contour_d(sil, up), True), ink=''.join(smooth_d(l) for l in h['lines']),
                hairSil=smooth_d(h['hair'], True), hair=smooth_d(h['hair'], True) + ''.join(smooth_d(c) for c in h['curls']),
                bandSil=band, band=smooth_d(bo) + smooth_d(bi))


FIG = {
    'handRwrite': dict(hand((200, 90, 490, 450), erase=[(0, 20, 58, 95)]), tip=[61.5, 78.5]),
    'handL': dict(hand((15, 95, 210, 455)), tip=[118, 106]),
    'handRsweep': dict(hand((1150, 85, 1448, 455), close_sides=.5), tip=[85, 125]),
    'handReraser': dict(hand((230, 625, 500, 1000), close_sides=.5), tip=[38, 61], elbow=[173, 375], sleeve=118),
    'catCurl': cat((225, 75, 610, 410)),
    'catLoaf': cat((815, 110, 1200, 410)),
    'catSit': cat((285, 590, 570, 940)),
    'head': head(),
}

if __name__ == '__main__':
    js = '// Generated by tools/trace/build_assets.py from the reference drawings. Do not edit by hand.\nexport const FIG = ' + json.dumps(FIG, separators=(',', ':')) + ';\n'
    open('site/js/figures.js', 'w').write(js)
    print({k: (v['w'], v['h'], len(v['ink'])) for k, v in FIG.items()}, len(js))
    # contact sheet
    x = 0; parts = []; H = 0
    for k, v in FIG.items():
        g = f'<g transform="translate({x} 0)"><path d="{v["sil"]}" fill="{"#dedcd8" if k.startswith("cat") else "#fcfbf8"}"/><path d="{v["ink"]}" fill="none" stroke="#232327" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/>'
        if 'hair' in v:
            g += f'<path d="{v["hairSil"]}" fill="#fcfbf8"/><path d="{v["hair"]}" fill="none" stroke="#232327" stroke-width="1.5" stroke-linecap="round"/><path d="{v["bandSil"]}" fill="#fcfbf8"/><path d="{v["band"]}" fill="none" stroke="#232327" stroke-width="1.5"/>'
        for key, col in (('tip', 'red'), ('elbow', 'blue')):
            if key in v:
                g += f'<circle cx="{v[key][0]}" cy="{v[key][1]}" r="3" fill="{col}"/>'
        parts.append(g + '</g>'); x += v['w'] + 10; H = max(H, v['h'])
    os.makedirs('tools/view', exist_ok=True)
    open('tools/view/sheet.svg', 'w').write(f'<svg xmlns="http://www.w3.org/2000/svg" width="{x}" height="{H}" viewBox="0 0 {x} {H}">' + ''.join(parts) + '</svg>')
